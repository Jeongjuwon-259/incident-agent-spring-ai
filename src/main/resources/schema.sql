CREATE TABLE IF NOT EXISTS svcm_tb_dept_info_master (
    dept_id         VARCHAR(20)  PRIMARY KEY,
    dept_name       VARCHAR(100) NOT NULL,
    parent_dept_id  VARCHAR(20),
    dept_head_name  VARCHAR(50),
    org_code        VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS svcm_tb_service_map_master (
    service_id    VARCHAR(20)  PRIMARY KEY,
    service_name  VARCHAR(100) NOT NULL,
    domain_name   VARCHAR(100),
    description   VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS svcm_tb_app_master (
    app_id       VARCHAR(20)  PRIMARY KEY,
    app_name     VARCHAR(100) NOT NULL,
    app_type     VARCHAR(20),
    service_id   VARCHAR(20),
    dept_id      VARCHAR(20),
    status       VARCHAR(20),
    criticality  VARCHAR(10),
    description  VARCHAR(500),
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS svcm_tb_svc_master (
    svc_id           VARCHAR(20) PRIMARY KEY,
    app_id           VARCHAR(20) NOT NULL,
    inspect_status   VARCHAR(20),
    approve_status   VARCHAR(20),
    approve_date     DATE,
    reviewer_id      VARCHAR(20),
    user_input_value VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS svcm_tb_user_info_master (
    user_id     VARCHAR(20)  PRIMARY KEY,
    user_name   VARCHAR(50)  NOT NULL,
    email       VARCHAR(100),
    phone       VARCHAR(30),
    dept_id     VARCHAR(20),
    emp_no      VARCHAR(20),
    job_title   VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS svcm_tb_app_user_map (
    map_id      VARCHAR(20) PRIMARY KEY,
    app_id      VARCHAR(20) NOT NULL,
    user_id     VARCHAR(20) NOT NULL,
    role_code   VARCHAR(20) NOT NULL,
    granted_at  DATE
);

CREATE TABLE IF NOT EXISTS svcm_tb_app_alias (
    alias_id    VARCHAR(20)  PRIMARY KEY,
    app_id      VARCHAR(20)  NOT NULL,
    alias_name  VARCHAR(100) NOT NULL,
    alias_type  VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS svcm_tb_jira_issue (
    issue_key     VARCHAR(30) PRIMARY KEY,
    project_key   VARCHAR(20),
    app_id        VARCHAR(20),
    assignee_id   VARCHAR(20),
    issue_type    VARCHAR(20),
    status        VARCHAR(20),
    summary       VARCHAR(300),
    worklog_hours DECIMAL(5,1),
    worklog_date  DATE
);

CREATE OR REPLACE VIEW svcm_vw_jira_dri_worklog AS
SELECT j.issue_key,
       j.project_key,
       j.app_id,
       a.app_name,
       j.assignee_id,
       u.user_name   AS assignee_name,
       d.dept_name   AS assignee_dept,
       j.issue_type,
       j.status,
       j.summary,
       j.worklog_hours,
       j.worklog_date
FROM svcm_tb_jira_issue j
LEFT JOIN svcm_tb_app_master a ON a.app_id = j.app_id
LEFT JOIN svcm_tb_user_info_master u ON u.user_id = j.assignee_id
LEFT JOIN svcm_tb_dept_info_master d ON d.dept_id = u.dept_id;

-- ---------------------------------------------------------------------
-- 2. 검증 SQL 시맨틱 캐시 (RAG)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS verified_sql_cache (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question        VARCHAR(1000) NOT NULL,
    sql_text        CLOB          NOT NULL,
    tables_csv      VARCHAR(500),
    parameters_json VARCHAR(2000),
    verified_by     VARCHAR(100)  NOT NULL,
    notes           VARCHAR(500),
    embedding_json  CLOB,
    tokens          VARCHAR(2000),
    use_count       INT DEFAULT 0,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cache_verified ON verified_sql_cache (verified_by);

-- ---------------------------------------------------------------------
-- 3. 감사 로그 (실행 단위) + LLM 호출 이력 + 멀티턴 대화
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agent_run (
    run_id          VARCHAR(40) PRIMARY KEY,
    user_id         VARCHAR(50),
    channel         VARCHAR(20),
    session_id      VARCHAR(60),
    question        VARCHAR(2000),
    status          VARCHAR(20),
    answer          CLOB,
    cache_hit       BOOLEAN DEFAULT FALSE,
    execution_count INT DEFAULT 0,
    llm_call_count  INT DEFAULT 0,
    iteration_count INT DEFAULT 0,
    duration_ms     BIGINT DEFAULT 0,
    error_message   VARCHAR(1000),
    started_at      TIMESTAMP,
    finished_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_run_session ON agent_run (session_id, started_at);

CREATE TABLE IF NOT EXISTS agent_run_step (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      VARCHAR(40) NOT NULL,
    seq_no      INT         NOT NULL,
    stage       VARCHAR(40) NOT NULL,
    summary     VARCHAR(500),
    detail      CLOB,
    latency_ms  BIGINT,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_step_run ON agent_run_step (run_id, seq_no);

CREATE TABLE IF NOT EXISTS agent_llm_call (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           VARCHAR(40),
    purpose          VARCHAR(40),
    provider         VARCHAR(80),
    model            VARCHAR(80),
    prompt           CLOB,
    response         CLOB,
    latency_ms       BIGINT,
    prompt_chars     INT,
    response_chars   INT,
    estimated_tokens INT,
    success          BOOLEAN,
    error_message    VARCHAR(1000),
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_llm_run ON agent_llm_call (run_id);

CREATE TABLE IF NOT EXISTS agent_conversation_turn (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  VARCHAR(60) NOT NULL,
    role        VARCHAR(20) NOT NULL,
    content     CLOB,
    run_id      VARCHAR(40),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_turn_session ON agent_conversation_turn (session_id, id);

-- ---------------------------------------------------------------------
-- 4. 품질 평가 하네스
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS eval_test_case (
    tc_id          VARCHAR(40) PRIMARY KEY,
    question       VARCHAR(2000) NOT NULL,
    expected_sql   CLOB NOT NULL,
    expected_answer CLOB,
    category       VARCHAR(40),
    enabled        BOOLEAN DEFAULT TRUE,
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS eval_batch (
    batch_id        VARCHAR(40) PRIMARY KEY,
    requested_by    VARCHAR(50),
    started_at      TIMESTAMP,
    finished_at     TIMESTAMP,
    status          VARCHAR(20),
    total_count     INT DEFAULT 0,
    completed_count INT DEFAULT 0,
    passed_count    INT DEFAULT 0,
    pass_rate       DECIMAL(5,2),
    note            VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS eval_case_result (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id               VARCHAR(40) NOT NULL,
    tc_id                  VARCHAR(40) NOT NULL,
    agent_run_id           VARCHAR(40),
    actual_sql             CLOB,
    actual_result          CLOB,
    final_answer           CLOB,
    question_snapshot      VARCHAR(2000),
    expected_sql_snapshot  CLOB,
    expected_answer_snapshot CLOB,
    ex_pass                BOOLEAN,
    ex_reason              VARCHAR(1000),
    aa_pass                BOOLEAN,
    aa_reason              VARCHAR(1000),
    fn_pass                BOOLEAN,
    fn_reason              VARCHAR(1000),
    exec_pass              BOOLEAN,
    exec_reason            VARCHAR(1000),
    overall_pass           BOOLEAN,
    overall_reason         VARCHAR(1000),
    duration_ms            BIGINT,
    created_at             TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_eval_result_batch ON eval_case_result (batch_id);
CREATE INDEX IF NOT EXISTS idx_eval_result_tc ON eval_case_result (tc_id, created_at);
