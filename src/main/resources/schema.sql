    use_count       INT DEFAULT 0,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cache_verified ON verified_sql_cache (verified_by);

-- ---------------------------------------------------------------------
-- 3. 감사 로그 (실행 단위) + LLM 호출 이력 + 멀티턴 대화
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agent_run (
    run_id          VARCHAR(40) PRIMARY KEY,
    user_id         VARCHAR(50),
    channel         VARCHAR(20),
    session_id      VARCHAR(60),
    question        VARCHAR(2000),
    status          VARCHAR(20),
    answer          CLOB,
    cache_hit       BOOLEAN DEFAULT FALSE,
    execution_count INT DEFAULT 0,
    llm_call_count  INT DEFAULT 0,
    iteration_count INT DEFAULT 0,
    duration_ms     BIGINT DEFAULT 0,
    error_message   VARCHAR(1000),
    started_at      TIMESTAMP,
    finished_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_run_session ON agent_run (session_id, started_at);

CREATE TABLE IF NOT EXISTS agent_run_step (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      VARCHAR(40) NOT NULL,
    seq_no      INT         NOT NULL,
    stage       VARCHAR(40) NOT NULL,
    summary     VARCHAR(500),
