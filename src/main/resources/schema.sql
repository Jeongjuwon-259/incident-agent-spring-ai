);
CREATE INDEX IF NOT EXISTS idx_llm_run ON agent_llm_call (run_id);

CREATE TABLE IF NOT EXISTS agent_conversation_turn (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  VARCHAR(60) NOT NULL,
